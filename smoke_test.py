#: Заведомо невалидный документ: нет заголовка, заглушка TODO, нет обязательных
#: разделов и нет списка требований.
BAD_DOCUMENT = """Заголовок без подчёркивания
TODO: дописать

Функциональные требования
#########################

просто текст без списка
"""


def main() -> int:
    failures: list[str] = []

    memo = get_analyst_memo()
    if "12 правил" not in memo or "Глоссарий" not in memo or "НБЦ" not in memo:
        failures.append("get_analyst_memo: памятка не содержит правил, глоссария или домена НБЦ")

    good_report = validate_bfr(GOOD_DOCUMENT)
    if "[FAIL]" in good_report:
        failures.append("validate_bfr: эталонный документ НБЦ не прошёл проверку\n" + good_report)
    if "Пройдено 12 из 12 правил" not in good_report:
        failures.append("validate_bfr: ожидалось «Пройдено 12 из 12 правил», получено иное")

    alt_report = validate_bfr(ALT_DOCUMENT)
    if "[FAIL]" in alt_report:
        failures.append("validate_bfr: документ со списками `#.` вместо csv-table не прошёл проверку\n" + alt_report)

    bad_report = validate_bfr(BAD_DOCUMENT)
    if "[FAIL]" not in bad_report:
        failures.append("validate_bfr: плохой документ ошибочно признан корректным")
    for code in ("R01", "R02", "R04"):
        if f"[FAIL] {code}" not in bad_report:
            failures.append(f"validate_bfr: правило {code} не сработало на плохом документе")

    empty_report = validate_bfr("   ")
    if "ОШИБКА" not in empty_report:
        failures.append("validate_bfr: пустой документ должен давать ошибку")

    if make_unified_diff(GOOD_DOCUMENT, GOOD_DOCUMENT) != "Изменений нет.":
        failures.append("make_unified_diff: одинаковые тексты должны давать «Изменений нет.»")

    patch = make_unified_diff(GOOD_DOCUMENT, GOOD_DOCUMENT.replace("Просматривает смены", "Читает смены"))
    if not patch.startswith("--- "):
        failures.append("make_unified_diff: патч не начинается с заголовка '--- '")

    save_result = save_bfr(GOOD_DOCUMENT, "smoke_test_output.rst")
    if "Сохранено" not in save_result:
        failures.append(f"save_bfr: не удалось сохранить документ: {save_result}")

    print(good_report)
    print()
    if failures:
        print("ПРОВЕРКА НЕ ПРОЙДЕНА:")
        for item in failures:
            print(f"  - {item}")
        return 1

    print("Все проверки пройдены: правила валидации БФТ НБЦ, патч и сохранение работают.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
